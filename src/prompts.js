// 简单的情感分析（基于中文关键词）
function analyzeEmotion(text) {
  const lower = text.toLowerCase();

  const patterns = [
    { keys: ['快乐', '开心', '高兴', '喜悦', '幸福', '美好', '棒', '太棒了', '好开心'], emotion: '喜悦', color: '#f4c542' },
    { keys: ['感谢', '感恩', '谢谢', '感激', '庆幸', '幸亏'], emotion: '感激', color: '#e8b87a' },
    { keys: ['希望', '期待', '未来', '梦想', '会好的', '相信'], emotion: '希望', color: '#7ec8a0' },
    { keys: ['爱', '喜欢', '温暖', '柔软', '心动'], emotion: '爱', color: '#e8917a' },
    { keys: ['悲伤', '难过', '伤心', '哭', '痛苦', '失去', '遗憾', '可惜'], emotion: '悲伤', color: '#7b9ec7' },
    { keys: ['害怕', '恐惧', '担心', '焦虑', '不安', '紧张', '慌'], emotion: '恐惧', color: '#b8a0d8' },
    { keys: ['生气', '愤怒', '讨厌', '烦', '火大', '受不了'], emotion: '愤怒', color: '#d4786e' },
    { keys: ['困惑', '迷茫', '不知道', '为什么', '搞不懂', '不明白'], emotion: '困惑', color: '#c0c0d0' },
    { keys: ['孤独', '寂寞', '一个人', '孤单', '没人'], emotion: '孤独', color: '#8899bb' },
    { keys: ['惊讶', '神奇', '不可思议', '哇', '天哪', '惊奇'], emotion: '惊奇', color: '#d4a574' },
    { keys: ['坚持', '努力', '加油', '一定', '必须', '坚定'], emotion: '坚定', color: '#8bb8a0' },
    { keys: ['想', '思考', '觉得', '认为', '也许', '可能'], emotion: '思考', color: '#9bb0d0' },
    { keys: ['灵感', '创意', '想法', '点子', '突然'], emotion: '灵感', color: '#f0d080' },
    { keys: ['安静', '宁静', '平和', '舒适', '放松', '惬意', '平静'], emotion: '宁静', color: '#b0d0c8' },
  ];

  for (const pattern of patterns) {
    for (const key of pattern.keys) {
      if (lower.includes(key)) {
        return { emotion: pattern.emotion, color: pattern.color };
      }
    }
  }

  return { emotion: '平静', color: '#a8d8c8' };
}

// 获取随机提示
function getRandomPrompt(category = 'daily') {
  const list = prompts[category] || prompts.daily;
  return list[Math.floor(Math.random() * list.length)];
}

// 获取今日提示（基于日期，保证同一天同样的问题）
function getDailyPrompt() {
  const today = new Date();
  const dayOfYear = Math.floor((today - new Date(today.getFullYear(), 0, 0)) / (1000 * 60 * 60 * 24));
  const list = prompts.daily;
  return list[dayOfYear % list.length];
}

